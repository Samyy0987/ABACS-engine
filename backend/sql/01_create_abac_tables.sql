-- 1. TABLE: ABAC_USERS
-- -----------------------------------------------------------------------------
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'ABAC_USERS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ABAC_USERS (
            id            VARCHAR2(36) NOT NULL,
            username      VARCHAR2(64) NOT NULL,
            email         VARCHAR2(255) NOT NULL,
            password_hash VARCHAR2(255) NOT NULL,
            is_active     NUMBER(1) DEFAULT 1 NOT NULL,
            is_verified   NUMBER(1) DEFAULT 0 NOT NULL,
            created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            updated_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT pk_abac_users PRIMARY KEY (id),
            CONSTRAINT uq_abac_users_username UNIQUE (username),
            CONSTRAINT uq_abac_users_email UNIQUE (email),
            CONSTRAINT chk_abac_users_active CHECK (is_active IN (0, 1)),
            CONSTRAINT chk_abac_users_verified CHECK (is_verified IN (0, 1))
        )';
    END IF;
